/// A Windows app's identity in one environment, from the `windows` section of upcode.yaml
/// (usually set per environment, under `env.<name>.windows`). Flutter has no flavors on Windows, so
/// `flutter:environment set` writes it where the Windows build reads it:
///
/// * `windows/environment.cmake`, included by `windows/CMakeLists.txt`: the executable's name and
///   the app's name, for its version resource and window title;
/// * `windows/environment.iss`, included by an Inno Setup script: the installer's app name,
///   executable and AppId.
class WindowsIdentity {
  const WindowsIdentity({required this.name, required this.binaryName, required this.installerId});

  /// Reads the identity from [config], the value of the `windows` key, or returns null when there is
  /// none. Throws an [ArgumentError] naming the key when a value is missing or malformed.
  static WindowsIdentity? fromConfig(Object? config) {
    if (config == null) {
      return null;
    }
    if (config is! Map) {
      throw ArgumentError.value(config, 'windows', 'must be a map with name, binary_name and installer_id');
    }

    final String name = _string(config, 'name');
    if (name.contains('"') || name.contains(r'\')) {
      throw ArgumentError.value(name, 'windows.name', 'may not contain " or \\');
    }
    final String binaryName = _string(config, 'binary_name');
    if (!RegExp(r'^[A-Za-z0-9_-]+$').hasMatch(binaryName)) {
      throw ArgumentError.value(binaryName, 'windows.binary_name', 'may contain only letters, digits, - and _');
    }
    final String installerId = _string(config, 'installer_id');
    if (!RegExp(r'^[0-9A-Fa-f]{8}(-[0-9A-Fa-f]{4}){3}-[0-9A-Fa-f]{12}$').hasMatch(installerId)) {
      throw ArgumentError.value(
        installerId,
        'windows.installer_id',
        'must be a GUID without braces, such as FD9718A0-AED3-4C67-AD70-FB4F40F11E2A',
      );
    }

    return WindowsIdentity(name: name, binaryName: binaryName, installerId: installerId.toUpperCase());
  }

  static String _string(Map<dynamic, dynamic> config, String key) {
    final Object? value = config[key];
    if (value is! String || value.trim().isEmpty) {
      throw ArgumentError.value(value, 'windows.$key', 'must be a non-empty string');
    }
    return value;
  }

  /// The name people see: the version resource's product name, the window title, the Start menu
  /// entry. Windows also names the app's data folder after it, so each environment keeps its own.
  final String name;

  /// The executable's name, without `.exe`.
  final String binaryName;

  /// The Inno Setup AppId. It is what lets an install upgrade in place, so it never changes once
  /// shipped, and each environment needs its own.
  final String installerId;

  /// The contents of `windows/environment.cmake`.
  String get cmake {
    return '# Generated by `upcode flutter:environment set` from the windows section of upcode.yaml.\n'
        '# Do not edit; it is rewritten for each environment.\n'
        'set(BINARY_NAME "$binaryName")\n'
        'set(APP_NAME "$name")\n';
  }

  /// The contents of `windows/environment.iss`. Inno Setup reads `{{` as a literal brace, which is
  /// how an AppId is written.
  String get innoSetup {
    return '; Generated by `upcode flutter:environment set` from the windows section of upcode.yaml.\n'
        '; Do not edit; it is rewritten for each environment.\n'
        '#define AppName "$name"\n'
        '#define AppExeName "$binaryName.exe"\n'
        '#define AppId "{{$installerId}"\n';
  }
}
